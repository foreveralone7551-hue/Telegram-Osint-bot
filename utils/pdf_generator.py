import os
import html
from datetime import datetime

def generate_html_report(title: str, data_dict: dict, filename: str = "report.html") -> str:
    """Генерирует красивый HTML-отчет с темной темой в стиле Aegis Recon."""
    
    rows_html = ""
    for key, value in data_dict.items():
        val_str = str(value)
        if val_str.startswith("http"):
            val_str = f'<a href="{val_str}" target="_blank">{val_str}</a>'
        
        rows_html += f"""
        <tr>
            <td class="key">{html.escape(str(key))}</td>
            <td class="value">{html.escape(val_str) if not val_str.startswith('http') else val_str}</td>
        </tr>
        """

    html_content = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>Aegis Recon - {html.escape(title)}</title>
    <style>
        :root {{
            --bg-color: #0d1117;
            --panel-bg: #161b22;
            --text-color: #c9d1d9;
            --accent-color: #58a6ff;
            --border-color: #30363d;
        }}
        body {{
            font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Helvetica, Arial, sans-serif;
            background-color: var(--bg-color);
            color: var(--text-color);
            margin: 0;
            padding: 20px;
            line-height: 1.5;
        }}
        .container {{
            max-width: 800px;
            margin: 0 auto;
        }}
        .header {{
            text-align: center;
            margin-bottom: 30px;
            padding-bottom: 20px;
            border-bottom: 1px solid var(--border-color);
        }}
        .header h1 {{
            color: #fff;
            margin: 0;
            font-size: 28px;
            letter-spacing: 1px;
        }}
        .header p {{
            color: #8b949e;
            font-size: 14px;
            margin-top: 5px;
        }}
        .report-card {{
            background-color: var(--panel-bg);
            border: 1px solid var(--border-color);
            border-radius: 8px;
            padding: 20px;
            box-shadow: 0 4px 6px rgba(0,0,0,0.3);
        }}
        .report-title {{
            font-size: 20px;
            color: var(--accent-color);
            margin-top: 0;
            margin-bottom: 20px;
            border-bottom: 1px solid var(--border-color);
            padding-bottom: 10px;
        }}
        table {{
            width: 100%;
            border-collapse: collapse;
        }}
        th, td {{
            padding: 12px;
            text-align: left;
            border-bottom: 1px solid var(--border-color);
        }}
        tr:last-child td {{
            border-bottom: none;
        }}
        td.key {{
            font-weight: 600;
            color: #8b949e;
            width: 40%;
        }}
        td.value {{
            color: #fff;
            word-break: break-all;
        }}
        a {{
            color: var(--accent-color);
            text-decoration: none;
        }}
        a:hover {{
            text-decoration: underline;
        }}
        .footer {{
            text-align: center;
            margin-top: 30px;
            color: #8b949e;
            font-size: 12px;
        }}
    </style>
</head>
<body>
    <div class="container">
        <div class="header">
            <h1>🛡️ Aegis Recon</h1>
            <p>OSINT Intelligence Report • Generated {datetime.now().strftime("%Y-%m-%d %H:%M:%S UTC")}</p>
        </div>
        
        <div class="report-card">
            <h2 class="report-title">Target: {html.escape(title)}</h2>
            <table>
                <tbody>
                    {rows_html}
                </tbody>
            </table>
        </div>
        
        <div class="footer">
            Generated by Aegis Recon. For legal use only. Do not misuse this tool.
        </div>
    </div>
</body>
</html>"""

    with open(filename, 'w', encoding='utf-8') as f:
        f.write(html_content)
        
    return filename
